// Scans public/videos for .mp4 clips and writes a sorted manifest that the
// VideoBackground component imports. Runs automatically on predev/prebuild, so
// dropping a new clip into public/videos is the only step needed to have it
// cycle in the background — no manual list to maintain.
//
// Regenerate manually with: npm run manifest:videos

import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const videosDir = join(projectRoot, "public", "videos");
const outFile = join(projectRoot, "src", "lib", "video-clips.ts");

/** Natural sort so clip-2 precedes clip-10. */
const naturalCompare = (a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" });

function collectClips() {
  let entries = [];
  try {
    entries = readdirSync(videosDir, { withFileTypes: true });
  } catch {
    console.warn(`[video-manifest] ${videosDir} not found — writing empty manifest`);
    return [];
  }
  return entries
    .filter((e) => e.isFile() && e.name.toLowerCase().endsWith(".mp4"))
    .map((e) => e.name)
    .sort(naturalCompare)
    .map((name) => `/videos/${name}`);
}

const clips = collectClips();

const body = `// AUTO-GENERATED by scripts/generate-video-manifest.mjs — do not edit by hand.
// Regenerate with: npm run manifest:videos
// This list is rebuilt on predev/prebuild from the contents of public/videos.

export const VIDEO_CLIPS: string[] = [
${clips.map((c) => `  ${JSON.stringify(c)},`).join("\n")}
];
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body, "utf8");
console.log(`[video-manifest] wrote ${clips.length} clip(s) to src/lib/video-clips.ts`);
